//! `fff setup --desktop` and `--file-chooser`: installs fff as the desktop's file manager (a desktop entry that
//! opens directories) and as the file chooser of
//! xdg-desktop-portal-termfilechooser (a wrapper script and the portal
//! settings that select it). Files fff generates carry [`MARKER`] and are
//! regenerated freely; anything else is never overwritten, and existing
//! configuration files are edited one key at a time.
use std::{
    fs,
    io::{self, Write},
    os::unix::fs::PermissionsExt,
    path::{Path, PathBuf},
    process::Command,
};

#[derive(Clone, Copy, Debug, PartialEq, Eq, clap::ValueEnum)]
pub enum Target {
    /// A desktop entry that opens directories in fff, made the default
    Desktop,
    /// fff as the xdg-desktop-portal file chooser (Firefox and others)
    FileChooser,
}

/// Marks files fff wrote, which it may replace.
const MARKER: &str = "Generated by fff setup";
/// The marker before setup was a command (0.8), still recognized.
const OLD_MARKER: &str = "Generated by fff --setup";
const WRAPPER: &str = include_str!("setup/file-chooser.sh");
const DESKTOP_ID: &str = "fff.desktop";
const FILE_CHOOSER_KEY: &str = "org.freedesktop.impl.portal.FileChooser";

/// Where setup reads and writes, from the XDG base directory variables.
pub struct Dirs {
    pub config_home: PathBuf,
    pub data_home: PathBuf,
    pub data_dirs: Vec<PathBuf>,
    /// `XDG_CURRENT_DESKTOP`: configuration may be specific to a desktop.
    pub desktops: Vec<String>,
}

impl Dirs {
    pub fn from_env() -> Result<Self, String> {
        let var = |name: &str| {
            std::env::var_os(name)
                .map(PathBuf::from)
                .filter(|p| p.is_absolute())
        };
        let home = var("HOME").ok_or("$HOME must be set to an absolute path")?;
        let data_dirs = std::env::var("XDG_DATA_DIRS")
            .ok()
            .filter(|d| !d.is_empty())
            .unwrap_or_else(|| "/usr/local/share:/usr/share".into());
        Ok(Self {
            config_home: var("XDG_CONFIG_HOME").unwrap_or_else(|| home.join(".config")),
            data_home: var("XDG_DATA_HOME").unwrap_or_else(|| home.join(".local/share")),
            data_dirs: data_dirs.split(':').map(PathBuf::from).collect(),
            desktops: std::env::var("XDG_CURRENT_DESKTOP")
                .unwrap_or_default()
                .split(':')
                .filter(|d| !d.is_empty())
                .map(String::from)
                .collect(),
        })
    }
}

/// Runs one setup, reporting each step to `out`. `terminal` is the
/// `[open] fff_terminal` command, split into words.
pub fn run(
    target: Target,
    dirs: &Dirs,
    fff: &Path,
    terminal: &[String],
    out: &mut dyn Write,
) -> Result<(), String> {
    let fff = fff
        .to_str()
        .filter(|s| !s.contains('\n'))
        .ok_or_else(|| format!("{}: unsupported path for a launcher", fff.display()))?;
    match target {
        Target::Desktop => desktop(dirs, fff, terminal, out),
        Target::FileChooser => file_chooser(dirs, fff, terminal, out),
    }
    .and_then(|()| {
        writeln!(
            out,
            "fff: its window opens with `{}` ([open] fff_terminal); to float it, add a \
             window manager rule, e.g. for i3:\n  \
             for_window [class=\"fff-picker\"] floating enable, resize set 1500 1000, \
             move position center",
            terminal.join(" ")
        )
    })
    .map_err(|e| e.to_string())
}

fn desktop(dirs: &Dirs, fff: &str, terminal: &[String], out: &mut dyn Write) -> io::Result<()> {
    let launcher = dirs.data_home.join("fff/open-folder");
    let written = generate(&launcher, &launcher_script(fff, terminal), 0o755)?;
    report(out, &launcher, written)?;
    let launcher = launcher
        .to_str()
        .ok_or_else(|| io::Error::other("the data directory is not UTF-8"))?;
    let applications = dirs.data_home.join("applications");
    let entry = applications.join(DESKTOP_ID);
    let written = generate(&entry, &desktop_entry(launcher), 0o644)?;
    report(out, &entry, written)?;
    // Refreshes mimeinfo.cache; launchers read the entry without it too.
    let _ = Command::new("update-desktop-database")
        .arg(&applications)
        .output();
    let previous = Command::new("xdg-mime")
        .args(["query", "default", "inode/directory"])
        .output();
    let Ok(previous) = previous else {
        writeln!(
            out,
            "fff: xdg-mime not found; make fff the default with\n  \
             xdg-mime default {DESKTOP_ID} inode/directory"
        )?;
        return Ok(());
    };
    let previous = String::from_utf8_lossy(&previous.stdout).trim().to_owned();
    // xdg-mime writes mimeapps.list there, and fails quietly (status 0)
    // when the directory is missing.
    fs::create_dir_all(&dirs.config_home)?;
    let status = Command::new("xdg-mime")
        .args(["default", DESKTOP_ID, "inode/directory"])
        .status()?;
    let now = Command::new("xdg-mime")
        .args(["query", "default", "inode/directory"])
        .output()?;
    if !status.success() || String::from_utf8_lossy(&now.stdout).trim() != DESKTOP_ID {
        return Err(io::Error::other(format!(
            "xdg-mime default {DESKTOP_ID} inode/directory did not take effect"
        )));
    }
    match previous.as_str() {
        "" | DESKTOP_ID => writeln!(out, "fff: directories now open in fff"),
        previous => writeln!(
            out,
            "fff: directories now open in fff (previously {previous}; \
             `xdg-mime default {previous} inode/directory` restores it)"
        ),
    }
}

/// The script the desktop entry runs: fff at a folder, inside the
/// configured terminal itself rather than with `Terminal=true`, whose
/// terminal each launcher picks from its own list (GIO's has no st, for one).
///
/// The terminal's own output is discarded: it would otherwise reach whatever
/// started the launcher (the shell that ran xdg-open), and terminals log the
/// escape sequences they do not support there (st does). A script keeps the
/// entry's Exec line free of quoting, which xdg-open without a desktop
/// environment does not understand: it splits the line at spaces.
pub fn launcher_script(fff: &str, terminal: &[String]) -> String {
    let command: Vec<String> = terminal
        .iter()
        .map(String::as_str)
        .chain([fff, "--browse", "--window"])
        .map(shell_quote)
        .collect();
    format!(
        "#!/bin/sh\n\
         # {MARKER} --desktop; running it again regenerates this file.\n\
         # Opens fff at a folder in a new terminal window, for fff.desktop.\n\
         exec {} \"$@\" >/dev/null 2>&1\n",
        command.join(" ")
    )
}

/// The desktop entry, running the launcher script.
pub fn desktop_entry(launcher: &str) -> String {
    format!(
        "# {MARKER} --desktop; running it again regenerates this file.\n\
         [Desktop Entry]\n\
         Type=Application\n\
         Name=fff\n\
         GenericName=File Manager\n\
         Comment=Browse folders with the fuzzy file finder\n\
         Exec={} %f\n\
         Terminal=false\n\
         Icon=system-file-manager\n\
         Categories=System;FileTools;FileManager;\n\
         Keywords=files;folders;directory;browser;\n\
         MimeType=inode/directory;\n",
        exec_word(launcher)
    )
}

/// Quotes one Exec argument as the desktop entry specification asks: quoted
/// when it holds reserved characters, `%` doubled, and backslashes doubled
/// once more because the whole value is itself an escaped string.
fn exec_word(word: &str) -> String {
    const RESERVED: &[char] = &[
        ' ', '\t', '"', '\'', '\\', '>', '<', '~', '|', '&', ';', '$', '*', '?', '#', '(', ')', '`',
    ];
    let word = word.replace('%', "%%");
    let word = if word.is_empty() || word.contains(RESERVED) {
        let mut quoted = String::from('"');
        for c in word.chars() {
            if matches!(c, '"' | '`' | '$' | '\\') {
                quoted.push('\\');
            }
            quoted.push(c);
        }
        quoted.push('"');
        quoted
    } else {
        word
    };
    word.replace('\\', "\\\\")
}

fn file_chooser(
    dirs: &Dirs,
    fff: &str,
    terminal: &[String],
    out: &mut dyn Write,
) -> io::Result<()> {
    let installed = std::iter::once(&dirs.data_home)
        .chain(&dirs.data_dirs)
        .any(|d| {
            d.join("xdg-desktop-portal/portals/termfilechooser.portal")
                .is_file()
        });
    if !installed {
        writeln!(
            out,
            "fff: xdg-desktop-portal-termfilechooser does not seem to be installed; \
             install it (https://github.com/hunkyburrito/xdg-desktop-portal-termfilechooser) \
             for this to take effect"
        )?;
    }
    let folder = dirs.config_home.join("xdg-desktop-portal-termfilechooser");
    let wrapper = folder.join("fff-wrapper.sh");
    let written = generate(&wrapper, &wrapper_script(fff, terminal), 0o755)?;
    report(out, &wrapper, written)?;
    let wrapper = wrapper
        .to_str()
        .ok_or_else(|| io::Error::other("the configuration directory is not UTF-8"))?;
    // The portal reads a file named after the desktop before `config`.
    let config = dirs
        .desktops
        .iter()
        .map(|d| folder.join(d))
        .find(|p| p.is_file())
        .unwrap_or_else(|| folder.join("config"));
    let written = edit(&config, |text| {
        let text = set_key(text, "filechooser", "cmd", wrapper, true);
        // The wrapper asks for the name itself; a help file would sit at the
        // suggested path as if it already existed.
        let text = set_key(&text, "filechooser", "create_help_file", "0", true);
        set_key(&text, "filechooser", "default_dir", "$HOME", false)
    })?;
    report(out, &config, written)?;
    // A desktop-specific file takes precedence over portals.conf.
    let portals = dirs.config_home.join("xdg-desktop-portal");
    let preferences = dirs
        .desktops
        .iter()
        .map(|d| portals.join(format!("{}-portals.conf", d.to_lowercase())))
        .find(|p| p.is_file())
        .unwrap_or_else(|| portals.join("portals.conf"));
    let written = edit(&preferences, |text| {
        set_key(text, "preferred", FILE_CHOOSER_KEY, "termfilechooser", true)
    })?;
    report(out, &preferences, written)?;
    writeln!(
        out,
        "fff: next, restart the portal:\n  \
         systemctl --user restart xdg-desktop-portal\n\
         and in Firefox's about:config set widget.use-xdg-desktop-portal.file-picker to 1,\n\
         then restart Firefox"
    )
}

/// The termfilechooser wrapper script for this fff binary and terminal.
pub fn wrapper_script(fff: &str, terminal: &[String]) -> String {
    let terminal: Vec<String> = terminal.iter().map(|w| shell_quote(w)).collect();
    WRAPPER
        .replace("@FFF@", &shell_quote(fff))
        .replace("@TERMINAL@", &terminal.join(" "))
}

fn shell_quote(word: &str) -> String {
    format!("'{}'", word.replace('\'', r"'\''"))
}

/// Writes a generated file unless something fff did not generate is there.
/// Returns whether the file changed.
fn generate(path: &Path, content: &str, mode: u32) -> io::Result<bool> {
    match fs::read_to_string(path) {
        Ok(old) if old == content => return Ok(false),
        Ok(old) if old.contains(MARKER) || old.contains(OLD_MARKER) => {}
        Err(e) if e.kind() == io::ErrorKind::NotFound => {}
        Ok(_) | Err(_) => {
            return Err(io::Error::other(format!(
                "{} exists and was not written by fff; move it aside and run this again",
                path.display()
            )));
        }
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, content)?;
    fs::set_permissions(path, fs::Permissions::from_mode(mode))?;
    Ok(true)
}

/// Rewrites a configuration file (created when missing) through `change`,
/// following symlinks and keeping permissions. Returns whether it changed.
fn edit(path: &Path, change: impl Fn(&str) -> String) -> io::Result<bool> {
    let old = match fs::read_to_string(path) {
        Ok(text) => text,
        Err(e) if e.kind() == io::ErrorKind::NotFound => String::new(),
        Err(e) => return Err(io::Error::new(e.kind(), format!("{}: {e}", path.display()))),
    };
    let new = change(&old);
    if new == old {
        return Ok(false);
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, new)?;
    Ok(true)
}

fn report(out: &mut dyn Write, path: &Path, written: bool) -> io::Result<()> {
    let state = if written { "wrote" } else { "unchanged" };
    writeln!(out, "fff: {state} {}", path.display())
}

/// Sets `key=value` in an INI-style file's `[section]`, leaving every other
/// line alone. An existing key is replaced only when `replace` is set; a
/// missing key goes right below the section header, and a missing section at
/// the end.
pub fn set_key(text: &str, section: &str, key: &str, value: &str, replace: bool) -> String {
    let line = format!("{key}={value}");
    let mut lines: Vec<&str> = text.lines().collect();
    let header = format!("[{section}]");
    let Some(start) = lines.iter().position(|l| l.trim() == header) else {
        let mut text = text.to_owned();
        if !text.is_empty() && !text.ends_with('\n') {
            text.push('\n');
        }
        if !text.is_empty() {
            text.push('\n');
        }
        return format!("{text}{header}\n{line}\n");
    };
    let end = lines[start + 1..]
        .iter()
        .position(|l| l.trim_start().starts_with('['))
        .map_or(lines.len(), |i| start + 1 + i);
    let existing = (start + 1..end).find(|&i| {
        lines[i]
            .split_once('=')
            .is_some_and(|(k, _)| k.trim() == key)
    });
    match existing {
        Some(_) if !replace => return text.to_owned(),
        Some(i) => lines[i] = &line,
        None => lines.insert(start + 1, &line),
    }
    let mut text = lines.join("\n");
    text.push('\n');
    text
}

#[cfg(test)]
mod tests {
    use super::*;

    fn scratch(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("fff-setup-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        dir
    }
    fn words(line: &str) -> Vec<String> {
        line.split(' ').map(String::from).collect()
    }

    #[test]
    fn set_key_edits_one_line_and_keeps_the_rest() {
        let conf = "# mine\n[preferred]\ndefault=gtk\n\n[other]\nx=1\n";
        assert_eq!(
            set_key(conf, "preferred", FILE_CHOOSER_KEY, "termfilechooser", true),
            format!(
                "# mine\n[preferred]\n{FILE_CHOOSER_KEY}=termfilechooser\ndefault=gtk\n\n[other]\nx=1\n"
            )
        );
        let set = format!("[preferred]\n{FILE_CHOOSER_KEY} = gtk\ndefault=gtk\n");
        assert_eq!(
            set_key(&set, "preferred", FILE_CHOOSER_KEY, "termfilechooser", true),
            format!("[preferred]\n{FILE_CHOOSER_KEY}=termfilechooser\ndefault=gtk\n")
        );
        // A key in another section is not this section's.
        assert_eq!(
            set_key("[a]\nk=1\n[b]\n", "b", "k", "2", true),
            "[a]\nk=1\n[b]\nk=2\n"
        );
        assert_eq!(set_key("[a]\nk=1", "a", "k", "2", false), "[a]\nk=1");
        assert_eq!(set_key("", "a", "k", "1", true), "[a]\nk=1\n");
        assert_eq!(set_key("x=1", "a", "k", "1", true), "x=1\n\n[a]\nk=1\n");
    }

    #[test]
    fn desktop_entry_runs_the_launcher_with_a_plain_exec_line() {
        // xdg-open splits Exec at spaces, so a usual path needs no quoting.
        let entry = desktop_entry("/home/me/.local/share/fff/open-folder");
        assert!(
            entry.contains("\nExec=/home/me/.local/share/fff/open-folder %f\n"),
            "{entry}"
        );
        assert!(entry.contains("MimeType=inode/directory;") && entry.contains(MARKER));
        assert!(desktop_entry("/a b/x").contains("\nExec=\"/a b/x\" %f\n"));
        assert_eq!(exec_word("100%"), "100%%");
        assert_eq!(exec_word(r#"a"$b"#), r#""a\\"\\$b""#);
        assert_eq!(exec_word(""), "\"\"");
    }

    #[test]
    fn launcher_runs_fff_in_the_terminal_without_its_output() {
        let dir = scratch("launcher");
        let terminal = dir.join("term");
        fs::write(
            &terminal,
            "#!/bin/sh\nprintf '%s\\n' \"$@\" >\"$ARGS\"\necho erresc >&2\necho out\n",
        )
        .unwrap();
        fs::set_permissions(&terminal, fs::Permissions::from_mode(0o755)).unwrap();
        let script = dir.join("open-folder");
        let terminal = vec![terminal.display().to_string(), "-c".into(), "it's".into()];
        fs::write(&script, launcher_script("/my fff", &terminal)).unwrap();
        fs::set_permissions(&script, fs::Permissions::from_mode(0o755)).unwrap();
        let output = Command::new(&script)
            .arg("/a dir")
            .env("ARGS", dir.join("args"))
            .output()
            .unwrap();
        assert!(output.status.success());
        assert!(
            output.stdout.is_empty() && output.stderr.is_empty(),
            "{output:?}"
        );
        assert_eq!(
            fs::read_to_string(dir.join("args")).unwrap(),
            "-c\nit's\n/my fff\n--browse\n--window\n/a dir\n"
        );
        fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn generated_files_never_replace_foreign_ones() {
        let dir = scratch("generate");
        let path = dir.join("f");
        assert!(generate(&path, "# Generated by fff setup\n1", 0o755).unwrap());
        assert!(!generate(&path, "# Generated by fff setup\n1", 0o755).unwrap());
        assert!(generate(&path, "# Generated by fff setup\n2", 0o755).unwrap());
        assert_eq!(
            fs::metadata(&path).unwrap().permissions().mode() & 0o777,
            0o755
        );
        fs::write(&path, "mine").unwrap();
        assert!(generate(&path, "# Generated by fff setup\n3", 0o755).is_err());
        assert_eq!(fs::read_to_string(&path).unwrap(), "mine");
        // Files from 0.8, written by `fff --setup`, are fff's too.
        fs::write(&path, "# Generated by fff --setup desktop\n").unwrap();
        assert!(generate(&path, "# Generated by fff setup\n4", 0o755).unwrap());
        fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn file_chooser_setup_writes_the_wrapper_and_selects_the_portal() {
        let dir = scratch("chooser");
        let dirs = Dirs {
            config_home: dir.join("config"),
            data_home: dir.join("data"),
            data_dirs: vec![],
            desktops: vec!["sway".into()],
        };
        let sway = dirs
            .config_home
            .join("xdg-desktop-portal/sway-portals.conf");
        fs::create_dir_all(sway.parent().unwrap()).unwrap();
        fs::write(&sway, "[preferred]\ndefault=wlr;gtk\n").unwrap();
        let mut out = Vec::new();
        run(
            Target::FileChooser,
            &dirs,
            Path::new("/bin/fff"),
            &words("st -e"),
            &mut out,
        )
        .unwrap();
        let out = String::from_utf8(out).unwrap();
        assert!(out.contains("does not seem to be installed"), "{out}");
        let folder = dirs.config_home.join("xdg-desktop-portal-termfilechooser");
        let wrapper = folder.join("fff-wrapper.sh");
        assert!(
            fs::read_to_string(&wrapper)
                .unwrap()
                .contains("fff='/bin/fff'")
        );
        assert_eq!(
            fs::read_to_string(folder.join("config")).unwrap(),
            format!(
                "[filechooser]\ndefault_dir=$HOME\ncreate_help_file=0\ncmd={}\n",
                wrapper.display()
            )
        );
        assert_eq!(
            fs::read_to_string(&sway).unwrap(),
            format!("[preferred]\n{FILE_CHOOSER_KEY}=termfilechooser\ndefault=wlr;gtk\n")
        );
        assert!(
            !dirs
                .config_home
                .join("xdg-desktop-portal/portals.conf")
                .exists()
        );
        // Running again changes nothing.
        let mut again = Vec::new();
        run(
            Target::FileChooser,
            &dirs,
            Path::new("/bin/fff"),
            &words("st -e"),
            &mut again,
        )
        .unwrap();
        assert!(!String::from_utf8(again).unwrap().contains("wrote"));
        fs::remove_dir_all(dir).unwrap();
    }

    /// Runs the wrapper as the portal would, with `env` as the terminal and a
    /// stand-in fff that prints `answer` and records its arguments and
    /// directory. Returns what the dialog received and fff's arguments.
    fn dialog(dir: &Path, args: [&str; 4], answer: &str) -> (String, String) {
        let stub = dir.join("stub");
        fs::write(
            &stub,
            "#!/bin/sh\n{ pwd; printf '%s\\n' \"$@\"; } >\"$ARGS\"\nprintf '%s' \"$ANSWER\"\n",
        )
        .unwrap();
        fs::set_permissions(&stub, fs::Permissions::from_mode(0o755)).unwrap();
        let wrapper = dir.join("wrapper.sh");
        fs::write(
            &wrapper,
            wrapper_script(stub.to_str().unwrap(), &words("env")),
        )
        .unwrap();
        fs::set_permissions(&wrapper, fs::Permissions::from_mode(0o755)).unwrap();
        let out = dir.join("out");
        let status = Command::new("bash")
            .arg(&wrapper)
            .args(args)
            .arg(&out)
            .env("ANSWER", answer)
            .env("ARGS", dir.join("args"))
            .env("HOME", dir)
            .env_remove("TERMCMD")
            .status()
            .unwrap();
        assert!(status.success());
        (
            fs::read_to_string(out).unwrap(),
            fs::read_to_string(dir.join("args")).unwrap(),
        )
    }

    #[test]
    fn wrapper_turns_portal_requests_into_fff_explorer() {
        let dir = scratch("wrapper");
        let home = dir.display();
        let (got, args) = dialog(&dir, ["0", "0", "0", ""], "/x/a\n");
        assert_eq!(got, "/x/a\n");
        assert_eq!(args, format!("{home}\nexplorer\n"));
        let (_, args) = dialog(&dir, ["1", "1", "0", "/x/y z"], "");
        assert_eq!(
            args,
            format!("{home}\nexplorer\n--multiple\n--directory\n/x/y z\n")
        );
        let (got, args) = dialog(&dir, ["0", "0", "1", "/x/page.html"], "");
        assert_eq!(got, "");
        assert_eq!(args, format!("{home}\nexplorer\n--save\n/x/page.html\n"));
        fs::remove_dir_all(dir).unwrap();
    }
}
